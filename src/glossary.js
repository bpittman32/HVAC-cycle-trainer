function tipFor(text) {
  let t = String(text).toLowerCase().replace(/\s+/g, ' ').trim();
  if (GLOSSARY[t]) return GLOSSARY[t];
  const s = t.replace(/^(condenser|evaporator|indoor|outdoor) /, '');
  if (GLOSSARY[s]) return GLOSSARY[s];
  const u = s.replace(/ (in|out)$/, '');
  return GLOSSARY[u] || null;
}
